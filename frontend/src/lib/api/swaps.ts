import { apiFetch } from "./client";
import type { ClothingItem } from "./clothingItems";

export type SwapStatus = "PENDING" | "ACCEPTED" | "REJECTED";

export type SwapExtraItem = {
  item: ClothingItem;
  addedAt: string;
  proposedByMe: boolean;
};

export type Swap = {
  id: number;
  matchId: number;
  status: SwapStatus;
  iAccepted: boolean;
  otherAccepted: boolean;
  reviewed: boolean;
  myReviewRating: number | null;
  myReviewComment: string | null;
  myReviewAutoGenerated: boolean | null;
  myExtraItems: SwapExtraItem[];
  otherExtraItems: SwapExtraItem[];
  cashAmountPence: number | null;
  iOweCash: boolean | null;
  updatedAt: string;
};

export function getSwap(matchId: number): Promise<Swap> {
  return apiFetch<Swap>(`/api/matches/${matchId}/swap`, {});
}

export function acceptSwap(matchId: number): Promise<Swap> {
  return apiFetch<Swap>(`/api/matches/${matchId}/swap/accept`, { method: "PATCH" });
}

export function rejectSwap(matchId: number): Promise<Swap> {
  return apiFetch<Swap>(`/api/matches/${matchId}/swap/reject`, { method: "PATCH" });
}

export function listOtherUserSwapItems(matchId: number): Promise<ClothingItem[]> {
  return apiFetch<ClothingItem[]>(`/api/matches/${matchId}/swap/other-items`, {});
}

export function addExtraItem(matchId: number, clothingItemId: number): Promise<Swap> {
  return apiFetch<Swap>(`/api/matches/${matchId}/swap/extra-items`, {
    method: "POST",
    body: JSON.stringify({ clothingItemId }),
  });
}

export function removeExtraItem(matchId: number, clothingItemId: number): Promise<Swap> {
  return apiFetch<Swap>(`/api/matches/${matchId}/swap/extra-items/${clothingItemId}`, {
    method: "DELETE",
  });
}

export function setCashTerm(matchId: number, amountPence: number, iOwe: boolean): Promise<Swap> {
  return apiFetch<Swap>(`/api/matches/${matchId}/swap/cash`, {
    method: "PUT",
    body: JSON.stringify({ amountPence, iOwe }),
  });
}

export function clearCashTerm(matchId: number): Promise<Swap> {
  return apiFetch<Swap>(`/api/matches/${matchId}/swap/cash`, { method: "DELETE" });
}

export type SwapHistoryEntry = {
  matchId: number;
  otherUserId: number;
  otherUsername: string;
  otherUserName: string;
  otherUserProfilePictureUrl: string | null;
  myItem: ClothingItem;
  otherItem: ClothingItem;
  myExtraItems: SwapExtraItem[];
  otherExtraItems: SwapExtraItem[];
  cashAmountPence: number | null;
  iOweCash: boolean | null;
  completedAt: string;
};

export function listSwapHistory(): Promise<SwapHistoryEntry[]> {
  return apiFetch<SwapHistoryEntry[]>("/api/swaps/history", {});
}
