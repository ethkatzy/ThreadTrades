"use client";

import { useEffect, useState } from "react";
import { useAuth } from "@/components/AuthProvider";
import { Pagination } from "@/components/Pagination";
import { deleteAdminReview, listAdminReviews, type PagedResponse } from "@/lib/api/admin";
import { ApiError } from "@/lib/api/client";
import type { Review } from "@/lib/api/reviews";

export default function AdminReviewsPage() {
  const { token } = useAuth();
  const [result, setResult] = useState<PagedResponse<Review> | null>(null);
  const [page, setPage] = useState(0);
  const [error, setError] = useState<string | null>(null);
  const [actionError, setActionError] = useState<string | null>(null);

  function load() {
    if (!token) {
      return;
    }
    listAdminReviews(token, page)
      .then((r) => {
        setResult(r);
        setError(null);
      })
      .catch(() => setError("Couldn't load reviews."));
  }

  useEffect(load, [token, page]);

  async function handleDelete(id: number) {
    if (!token) {
      return;
    }
    setActionError(null);
    try {
      await deleteAdminReview(token, id);
      load();
    } catch (err) {
      setActionError(err instanceof ApiError ? err.message : "Couldn't delete this review.");
    }
  }

  return (
    <div className="flex flex-col gap-4">
      <h2 className="text-lg font-medium">Reviews</h2>

      {error && <p className="text-sm text-red-600">{error}</p>}
      {actionError && <p className="text-sm text-red-600">{actionError}</p>}

      {result && (
        <ul className="flex flex-col gap-2">
          {result.content.map((review) => (
            <li
              key={review.id}
              className="flex items-start justify-between gap-3 rounded border border-black/10 p-3 text-sm dark:border-white/20"
            >
              <div className="min-w-0">
                <p className="text-xs text-zinc-600 dark:text-zinc-400">
                  Swap #{review.swapId} · {review.reviewerUsername} · {review.rating}★
                  {review.autoGenerated ? " (auto)" : ""} · {new Date(review.createdAt).toLocaleString()}
                </p>
                {review.comment && <p className="break-words">{review.comment}</p>}
              </div>
              <button
                type="button"
                onClick={() => handleDelete(review.id)}
                className="shrink-0 rounded border border-black/10 px-3 py-1 text-xs dark:border-white/20"
              >
                Delete
              </button>
            </li>
          ))}
          {result.content.length === 0 && (
            <p className="py-4 text-center text-sm text-zinc-600 dark:text-zinc-400">No reviews found.</p>
          )}
        </ul>
      )}

      {result && <Pagination page={result.page} totalPages={result.totalPages} onPageChange={setPage} />}
    </div>
  );
}
