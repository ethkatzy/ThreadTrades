-- Extra items either side proposes adding to their side of an already-matched
-- swap, to balance a value difference. Not an entity collection on Swap --
-- like every other related-row table (message, review), it's fetched via its
-- own repository and joined at the service layer (see V1 header comment).
CREATE TABLE swap_extra_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    swap_id          BIGINT NOT NULL REFERENCES swap (id) ON DELETE CASCADE,
    side             VARCHAR(1) NOT NULL CHECK (side IN ('A', 'B')),
    clothing_item_id BIGINT NOT NULL REFERENCES clothing_item (id) ON DELETE CASCADE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (swap_id, clothing_item_id)
);

CREATE INDEX idx_swap_extra_item_swap ON swap_extra_item (swap_id);

-- Plain tracked cash figure to balance a value difference -- settled by the
-- users themselves (bank transfer/PayPal), never processed in-app. Both null
-- (no cash term) or both set; amount must be positive.
ALTER TABLE swap
    ADD COLUMN cash_amount_pence BIGINT,
    ADD COLUMN cash_owed_by_side VARCHAR(1) CHECK (cash_owed_by_side IN ('A', 'B')),
    ADD CONSTRAINT swap_cash_both_or_neither
        CHECK ((cash_amount_pence IS NULL) = (cash_owed_by_side IS NULL)),
    ADD CONSTRAINT swap_cash_amount_positive
        CHECK (cash_amount_pence IS NULL OR cash_amount_pence > 0);
