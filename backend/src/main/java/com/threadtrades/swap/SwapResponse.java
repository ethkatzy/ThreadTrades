package com.threadtrades.swap;

import java.time.Instant;
import java.util.List;

public record SwapResponse(
        Long id,
        Long matchId,
        SwapStatus status,
        boolean iAccepted,
        boolean otherAccepted,
        boolean reviewed,
        Integer myReviewRating,
        String myReviewComment,
        Boolean myReviewAutoGenerated,
        List<SwapExtraItemResponse> myExtraItems,
        List<SwapExtraItemResponse> otherExtraItems,
        Long cashAmountPence,
        Boolean iOweCash,
        Instant updatedAt) {

    public static SwapResponse from(
            Swap swap,
            Long viewerProfileId,
            boolean reviewed,
            Integer myReviewRating,
            String myReviewComment,
            Boolean myReviewAutoGenerated,
            List<SwapExtraItem> extraItems) {
        boolean viewerIsA = swap.getMatch().getUserA().getId().equals(viewerProfileId);
        TradeSide viewerSide = viewerIsA ? TradeSide.A : TradeSide.B;
        boolean iAccepted = viewerIsA ? swap.isAcceptedByUserA() : swap.isAcceptedByUserB();
        boolean otherAccepted = viewerIsA ? swap.isAcceptedByUserB() : swap.isAcceptedByUserA();
        List<SwapExtraItemResponse> myExtraItems = extraItems.stream()
                .filter(extraItem -> extraItem.getSide() == viewerSide)
                .map(extraItem -> SwapExtraItemResponse.from(extraItem, viewerSide))
                .toList();
        List<SwapExtraItemResponse> otherExtraItems = extraItems.stream()
                .filter(extraItem -> extraItem.getSide() != viewerSide)
                .map(extraItem -> SwapExtraItemResponse.from(extraItem, viewerSide))
                .toList();
        Boolean iOweCash = swap.hasCashTerm() ? swap.getCashOwedBySide() == viewerSide : null;
        return new SwapResponse(
                swap.getId(),
                swap.getMatch().getId(),
                swap.getStatus(),
                iAccepted,
                otherAccepted,
                reviewed,
                myReviewRating,
                myReviewComment,
                myReviewAutoGenerated,
                myExtraItems,
                otherExtraItems,
                swap.getCashAmountPence(),
                iOweCash,
                swap.getUpdatedAt());
    }
}
